export function reportEditorialInput(period:ReportPeriod,facts:ReportFacts[]):string{
 const babies=facts.map(f=>({
  name:f.name,counts:f.counts,
  moments:f.moments.map(m=>({day:m.day,title:m.title,description:m.description.slice(0,200)})),
  media:f.media.map(m=>({...m,caption:m.caption.slice(0,180)}))
 }));
 let result=JSON.stringify({period,babies});
 // Never truncate JSON halfway through a record: trim older source stories if
 // a multi-baby month approaches the model's input budget. Counts remain exact.
 while(result.length>14500){
  let index=-1,maximum=0;
  for(let i=0;i<babies.length;i++){
   const size=babies[i].moments.length+babies[i].media.length;
   if(size>maximum){index=i;maximum=size}
  }
  if(index<0)break;
  if(babies[index].moments.length>=babies[index].media.length)babies[index].moments.pop();
  else babies[index].media.pop();
  result=JSON.stringify({period,babies});
 }
 return result;
}
const clean=(v:unknown,max:number)=>typeof v==='string'?v.replace(/[\u0000-\u001f\u007f]+/g,' ').replace(/\s+/g,' ').trim().slice(0,max):'';
export function parseReportNarrative(raw:unknown):ReportNarrative{
 if(typeof raw!=='string')throw Error('REPORT_AI_INVALID_RESPONSE');
 const stripped=raw.trim().replace(/^\x60{3}(?:json)?\s*/i,'').replace(/\s*\x60{3}$/,'').trim();
 let parsed:unknown;
 try{parsed=JSON.parse(stripped)}catch{throw Error('REPORT_AI_INVALID_RESPONSE')}
 if(!parsed||typeof parsed!=='object'||Array.isArray(parsed))throw Error('REPORT_AI_INVALID_RESPONSE');
 const obj=parsed as Record<string,unknown>;
 const title=clean(obj.title,24);
 const paragraphs=Array.isArray(obj.paragraphs)?obj.paragraphs.map(p=>clean(p,270)).filter(p=>p.length>=10).slice(0,4):[];
 if(title.length<2||!paragraphs.length)throw Error('REPORT_AI_INVALID_RESPONSE');
 return {title,paragraphs};
}
function reportHeader(period:ReportPeriod,facts:ReportFacts[]):string{
 const name=facts.length===1?facts[0].name:'家人';
 const title=period.kind==='week'?name+'的这一周':name+'的'+Number(period.start.slice(5,7))+'月成长记';
 const when=period.kind==='week'?monthDay(period.start)+' — '+monthDay(period.end):
  period.start.slice(0,4)+'年'+Number(period.start.slice(5,7))+'月';
 return '🌱 '+title+'\n'+when+' · BabyMemo '+(period.kind==='week'?'成长周报':'成长月报');
}
export function renderFamilyReport(period:ReportPeriod,facts:ReportFacts[],narrative:ReportNarrative):string{
 const paragraphs=narrative.paragraphs.slice(0,period.kind==='week'?3:4).join('\n\n').slice(0,period.kind==='week'?560:760);
 const intro=reportHeader(period,facts)+'\n\n'+narrative.title+'\n\n'+paragraphs;
 const footer='\n\n📒 本期成长足迹\n';
 const sections=facts.filter(f=>Object.values(f.counts).some(v=>v>0)).map(f=>(
  (facts.length===1?'':'【'+f.name+'】\n')+
  '✨ '+f.counts.moments+' 个瞬间 · 📷 '+f.counts.photos+' 张照片 · 🎬 '+f.counts.videos+' 段视频'+
  (f.metrics.length?'\n📏 '+f.metrics.join('；'):'')
 ));
 const remaining=Math.max(0,1730-intro.length-footer.length);
 let summary='',included=0;
 for(const block of sections){
  const next=(summary?'\n\n':'')+block;
  if(summary.length+next.length>remaining)break;
  summary+=next;included++;
 }
 if(!summary)summary='更多记录请在 BabyMemo 查看';
 else if(included<sections.length&&summary.length+25<remaining)summary+='\n更多记录请在 BabyMemo 查看';
 return (intro+footer+summary).slice(0,1750);
}
