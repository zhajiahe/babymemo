import type {ReportKind,ReportPeriod} from './family-report-schedule';

// Verified figures come from D1; AI contributes only the title and narrative.
export type ReportGrowth={day:string;weight:number|null;height:number|null;head_circumference:number|null};
export type ReportMoment={day:string;title:string;description:string};
export type ReportMedia=ReportMoment & {mime:string};
export type ReportFacts={
 name:string;
 counts:{moments:number;photos:number;videos:number;measurements:number};
 metrics:string[];
 moments:ReportMoment[];
 media:{day:string;type:'照片'|'视频';caption:string}[];
};
export type ReportNarrative={title:string;paragraphs:string[]};
const fmt=(n:number)=>String(Math.round(n*100)/100);
const monthDay=(day:string)=>Number(day.slice(5,7))+'月'+Number(day.slice(8,10))+'日';
const dayGap=(a:string,b:string)=>(Date.parse(a+'T00:00:00Z')-Date.parse(b+'T00:00:00Z'))/86400000;
export function reportMetrics(current:ReportGrowth[],prior:ReportGrowth[],kind:ReportKind):string[]{
 const fields:[keyof Omit<ReportGrowth,'day'>,string,string][]=[
  ['weight','体重','kg'],['height','身高','cm'],['head_circumference','头围','cm']
 ];
 return fields.flatMap(([key,label,unit])=>{
  const sorted=[...current].sort((a,b)=>b.day.localeCompare(a.day));
  const latest=sorted.find(item=>typeof item[key]==='number'&&Number.isFinite(item[key]));
  if(!latest)return [];
  const base=label+' '+fmt(latest[key] as number)+' '+unit+'（'+monthDay(latest.day)+'测量）';
  // Even an accurate July-to-October delta must not masquerade as weekly growth.
  if(kind!=='month')return [base];
  const older=[...sorted,...prior].filter(row=>row.day<latest.day).sort((a,b)=>b.day.localeCompare(a.day))
   .find(row=>typeof row[key]==='number'&&Number.isFinite(row[key]));
  if(!older||dayGap(latest.day,older.day)>45)return [base];
  const delta=Math.round(((latest[key] as number)-(older[key] as number))*100)/100;
  return [base+'；较'+monthDay(older.day)+(delta>0?'+':'')+fmt(delta)+' '+unit];
 });
}
export function isGenericMediaTitle(value:string):boolean{
 const title=value.trim();
 if(!title)return true;
 // Ignore names generated by WeChat, cameras, phones or file exporters.
 return /^(?:微信(?:照片|图片|视频|文件)(?:\s*[-_：: ]?\s*[\d年月日Tt :./_-]+)?|(?:img|vid|dsc|mov|pxl|mmexport|wx_img|screenshot|image|video)[_\s-]?[a-z0-9._:\s-]+)$/i.test(title);
}
export function reportMediaStories(rows:ReportMedia[],limit:number):ReportFacts['media']{
 const result:ReportFacts['media']=[];
 for(const item of rows){
  const description=item.description.trim(),title=item.title.trim();
  const caption=description&&!isGenericMediaTitle(description)?description:!isGenericMediaTitle(title)?title:'';
  if(!caption)continue;
  result.push({day:item.day,type:item.mime.startsWith('video/')?'视频':'照片',caption:caption.slice(0,240)});
  if(result.length>=limit)break;
 }
 return result;
}
